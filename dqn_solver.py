@dataclass
class ReplayBuffer:
    capacity: int
    state_dim: int
    action_dim: int

    def __post_init__(self):
        self.states = np.zeros((self.capacity, self.state_dim), np.float32)
        self.actions = np.zeros((self.capacity, self.action_dim), np.float32)
        self.goals = np.zeros((self.capacity, self.state_dim), np.float32)
        self.rewards = np.zeros(self.capacity, np.float32)
        self.next_states = np.zeros((self.capacity, self.state_dim), np.float32)
        self.dones = np.zeros(self.capacity, np.float32)
        self.ptr = 0
        self.size = 0

    def add(self, state, action, reward, next_state, done, goal):
        i = self.ptr
        self.states[i] = state
        self.actions[i] = action
        self.rewards[i] = reward
        self.next_states[i] = next_state
        self.dones[i] = float(done)
        self.ptr = (self.ptr + 1) % self.capacity
        self.size = min(self.size + 1, self.capacity)
        self.goals[i] = goal

    def sample(self, batch_size, rng):
        idx = rng.integers(0, self.size, size=batch_size)
        return tuple(torch.as_tensor(x[idx]) for x in (
            self.states, self.actions, self.rewards,
            self.next_states, self.dones, self.goals
        ))

    def reset(self):
        self.ptr = 0 
        self.size = 0


class MLP(torch.nn.Module):
    def __init__(self, input_dim, output_dim, hidden_dim=256):
        super().__init__()
        self.net = torch.nn.Sequential(
            torch.nn.Linear(input_dim, hidden_dim),
            torch.nn.ReLU(),
            torch.nn.Linear(hidden_dim, hidden_dim),
            torch.nn.ReLU(),
            torch.nn.Linear(hidden_dim, output_dim),
        )

    def forward(self, x):
        return self.net(x)


class GoalConditionedCritic(torch.nn.Module):
    """Goal-conditioned Q(z, a, g)."""

    def __init__(self, state_dim, action_dim, hidden_dim=256):
        super().__init__()
        self.net = MLP(2 * state_dim + action_dim, 1, hidden_dim)

    def forward(self, state, action, goal):
        return self.net(torch.cat((state, action, goal), dim=-1)).squeeze(-1)


class GoalConditionedActor(torch.nn.Module):
    """Deterministic goal-conditioned policy pi(z, g)."""

    def __init__(self, state_dim, action_dim, low, high, hidden_dim=256):
        super().__init__()
        self.net = MLP(2 * state_dim, action_dim, hidden_dim)
        self.register_buffer("action_low", torch.as_tensor(low, dtype=torch.float32))
        self.register_buffer("action_high", torch.as_tensor(high, dtype=torch.float32))

    def forward(self, state, goal):
        x = torch.tanh(self.net(torch.cat((state, goal), dim=-1)))
        center = (self.action_high + self.action_low) / 2
        scale = (self.action_high - self.action_low) / 2
        return center + scale  * x


class DeepQSolver:
    """Goal-conditioned deep Q-learning solver in latent space.

    For continuous Box actions this uses an actor-critic formulation:
    the critic learns Q(z, a, g), while the actor learns the approximately
    greedy policy pi(z, g) = argmax_a Q(z, a, g).

    Imagined transitions are generated by the supplied world model. Like the
    MCTS/RRT solvers, the world model's `predict` expects a rolling window of
    `model.predictor.num_frames` past latents/actions rather than a single
    latent, so a sliding-window history is maintained here as well.
    """

    def __init__(
        self,
        model: Any,
        batch_size: int = 64,
        planning_iterations: int = 5,
        planning_horizon: int = 20,
        rollout_batch_size: int = 64,
        train_steps: int = 200,
        replay_capacity: int = 100_000,
        warmup_size: int = 1_000,
        gamma: float = 0.99,
        actor_lr: float = 1e-4,
        critic_lr: float = 1e-3,
        tau: float = 0.005,
        exploration_std: float = 1.0,
        action_cost: float = 0.0,
        goal_radius: float = 0.05,
        hidden_dim: int = 256,
        device: str | torch.device = "cpu",
        seed: int = 1234,
        **kwargs,
    ):
        self.model = model
        self.batch_size = batch_size
        self.planning_iterations = planning_iterations
        self.planning_horizon = planning_horizon
        self.rollout_batch_size = rollout_batch_size
        self.train_steps = train_steps
        self.replay_capacity = replay_capacity
        self.warmup_size = warmup_size
        self.gamma = gamma
        self.actor_lr = actor_lr
        self.critic_lr = critic_lr
        self.tau = tau
        self.exploration_std = exploration_std
        self.action_cost = action_cost
        self.goal_radius = goal_radius
        self.hidden_dim = hidden_dim
        self.rng = np.random.default_rng(seed)
        self.callbacks = []
        self._configured = False
        self._networks_initialized = False
        self._last_q_loss = None
        self._last_actor_loss = None
        self._history_size = 1
        self.action_block = None

        # Match MCTS/RRT: infer device/dtype from the shared world model
        # rather than always defaulting to the constructor's "cpu" default,
        # so this solver stays compatible with a model living on GPU.
        try:
            params = list(model.parameters())
            if params:
                self.device = params[0].device
                self._dtype = params[0].dtype
            else:
                self.device = torch.device(device)
                self._dtype = torch.float32
        except (AttributeError, StopIteration):
            self.device = torch.device(device)
            self._dtype = torch.float32

    def configure(self, *, action_space: gym.Space, n_envs: int, config: Any):
        self._action_space = action_space
        self._n_envs = n_envs
        self._config = config
        self._action_dim_base = int(np.prod(action_space.shape[1:]))
        self.action_block = config.action_block
        self._action_dim = self._action_dim_base * config.action_block
        self._configured = True

    @property
    def n_envs(self):
        return self._n_envs

    @property
    def action_dim(self):
        return self._action_dim

    @property
    def horizon(self):
        return self._config.horizon

    def __call__(self, *args, **kwargs):
        return self.solve(*args, **kwargs)

    def _init_networks(self, state_dim):
        if self._networks_initialized:
            return

        low, high = self._get_action_bounds()

        self.actor = GoalConditionedActor(
            state_dim, self.action_dim, low, high, self.hidden_dim
        ).to(self.device, dtype=self._dtype)
        self.actor_target = GoalConditionedActor(
            state_dim, self.action_dim, low, high, self.hidden_dim
        ).to(self.device, dtype=self._dtype)

        self.critic = GoalConditionedCritic(
            state_dim, self.action_dim, self.hidden_dim
        ).to(self.device, dtype=self._dtype)
        self.critic_target = GoalConditionedCritic(
            state_dim, self.action_dim, self.hidden_dim
        ).to(self.device, dtype=self._dtype)

        self.actor_target.load_state_dict(self.actor.state_dict())
        self.critic_target.load_state_dict(self.critic.state_dict())

        self.actor_optimizer = torch.optim.Adam(
            self.actor.parameters(), lr=self.actor_lr
        )
        self.critic_optimizer = torch.optim.Adam(
            self.critic.parameters(), lr=self.critic_lr
        )

        self.replay = ReplayBuffer(
            self.replay_capacity, state_dim, self.action_dim
        )

        # Same convention as MCTS/RRT: the world model's predictor consumes
        # a rolling window of this many past (latent, action) steps.
        self._history_size = int(getattr(self.model.predictor, "num_frames", 1))

        self._networks_initialized = False #OPTIONNEL

    def _select(self, value, idx):
        if torch.is_tensor(value) or isinstance(value, (np.ndarray, list, tuple)):
            return value[idx]
        return value

    def _extract_latent_vector(self, emb):
        if emb is None:
            raise ValueError("encoded embedding is missing")
        emb = torch.as_tensor(emb).detach().cpu().float()
        if emb.dim() == 3:
            return emb[0, -1].numpy().astype(np.float32)
        if emb.dim() == 2:
            return emb[-1].numpy().astype(np.float32)
        if emb.dim() == 1:
            return emb.numpy().astype(np.float32)
        return emb.reshape(-1, emb.shape[-1])[-1].numpy().astype(np.float32)

    def _state_from_info(self, info_dict):
        if not hasattr(self.model, "encode"):
            raise ValueError("model does not support encoding")

        sample = dict(info_dict)
        for k in ("goal", "goal_pixels", "goal_proprio", "action"):
            sample.pop(k, None)
        sample["pixels"] = info_dict["pixels"].unsqueeze(1).to(
            device=self.device, dtype=self._dtype
        )

        emb = self.model.encode(sample).get("emb")
        if emb is None:
            raise ValueError("encoded embedding is missing")
        return self._extract_latent_vector(emb)

    def _goal_from_info(self, info_dict):
        if not hasattr(self.model, "encode"):
            raise ValueError("model does not support encoding")

        sample = dict(info_dict)
        sample["pixels"] = info_dict["goal"].unsqueeze(1).to(
            device=self.device, dtype=self._dtype
        )
        for k in list(info_dict):
            if k.startswith("goal_"):
                sample[k[len("goal_"):]] = sample.pop(k)
        sample.pop("action", None)

        emb = self.model.encode(sample).get("emb")
        if emb is None:
            raise ValueError("encoded embedding is missing")
        return self._extract_latent_vector(emb)

    def _init_history(self, root_state: np.ndarray, n: int) -> tuple[np.ndarray, np.ndarray]:
        """Build a fresh (n, history_size, dim) window seeded from root_state.

        Mirrors the padding convention used by MCTS/RRT for nodes with no
        real parent history: repeat the current state across the window and
        start with zero actions.
        """
        state_history = np.repeat(
            root_state[None, None, :], self._history_size, axis=1
        )
        state_history = np.repeat(state_history, n, axis=0).astype(np.float32)
        action_history = np.zeros(
            (n, self._history_size, self.action_dim), dtype=np.float32
        )
        return state_history, action_history

    def _transition_latent(self, state_history, action_history):
        """Predict the next latent from a (batch, history_size, dim) window."""
        if not hasattr(self.model, "predict") or not hasattr(self.model, "action_encoder"):
            raise ValueError("model does not support latent prediction")

        current_t = torch.as_tensor(state_history, dtype=self._dtype, device=self.device)
        action_t = torch.as_tensor(action_history, dtype=self._dtype, device=self.device)

        pred = self.model.predict(current_t, self.model.action_encoder(action_t))

        if not torch.is_tensor(pred):
            raise ValueError("world model prediction is not a tensor")

        pred = pred.detach().cpu().numpy().astype(np.float32)

        if pred.shape[-1] != state_history.shape[-1]:
            raise ValueError(
                f"predicted embedding dim {pred.shape[-1]} does not match "
                f"latent dim {state_history.shape[-1]}"
            )
        return pred[:,-1]
    
    def _get_action_bounds(self):
        low = np.asarray(self._action_space.low[0], dtype=np.float32).reshape(-1)
        high = np.asarray(self._action_space.high[0], dtype=np.float32).reshape(-1)
        num_repeat = self.action_block
        return low.repeat(num_repeat), high.repeat(num_repeat)


    def _reward(self, state, next_state, goal, action):
        distance = np.linalg.norm(state - goal, axis=-1) 
        distance_next = np.linalg.norm(next_state - goal, axis=-1)
        reward =  distance - distance_next - self.action_cost
        done = distance_next <= self.goal_radius
        return reward.astype(np.float32), done

    def _random_action(self, n):
        if not isinstance(self._action_space, Box):
            return self.rng.normal(0.5,0.25,size=(n, self.action_dim)).astype(np.float32)

        low = np.asarray(self._action_space.low[0], dtype=np.float32).reshape(-1)
        high = np.asarray(self._action_space.high[0], dtype=np.float32).reshape(-1)

        mean = (low + high) / 2.0
        std = (high - low) / 2.0

        num_repeat = self.action_block

        actions = self.rng.normal(mean.repeat(num_repeat,0), std.repeat(num_repeat,0), size=(n, self.action_dim))

        return actions.astype(np.float32)

    def _policy_action(self, states, goals, explore=True):
        with torch.no_grad():
            s = torch.as_tensor(states, dtype=self._dtype, device=self.device)
            g = torch.as_tensor(goals, dtype=self._dtype, device=self.device)
            action = self.actor(s, g)

            if explore:
                action = action + self.exploration_std * torch.randn_like(action)

            low, high = self._get_action_bounds()
            low = torch.as_tensor(low, dtype=self._dtype, device=self.device)
            high = torch.as_tensor(high, dtype=self._dtype, device=self.device)

            action = torch.clamp(action, low, high)

        return action.cpu().numpy().astype(np.float32)

    def _collect_imagined_data(self, root_state, goal_state, n_rollouts):
        states = np.repeat(root_state[None], n_rollouts, axis=0)
        goals = np.repeat(goal_state[None], n_rollouts, axis=0)
        active = np.ones(n_rollouts, dtype=bool)

        state_history, action_history = self._init_history(root_state, n_rollouts)

        for t in range(self.planning_horizon):
            if not np.any(active):
                break

            idx = np.flatnonzero(active)
            current = states[idx]
            current_goals = goals[idx]

            if self.replay.size < self.warmup_size:
                actions = self._random_action(len(idx))
            else:
                actions = self._policy_action(
                    current, current_goals, explore=True
                )

            step_action_history = np.concatenate(
                [action_history[idx, 1:], actions[:, None, :]], axis=1
            )

            next_states = self._transition_latent(
                state_history[idx,-min(self._history_size,t+1):], step_action_history[:,-min(self._history_size,t+1):]
            )
            rewards, dones = self._reward(current,
                next_states, goal_state, actions
            )

            for j, i in enumerate(idx):
                self.replay.add(
                    states[i], actions[j], rewards[j],
                    next_states[j], dones[j], goals[j]
                )
                states[i] = next_states[j]
                state_history[i] = np.concatenate(
                    [state_history[i, 1:], next_states[j][None, :]], axis=0
                )
                action_history[i] = step_action_history[j]
                if dones[j]:
                    active[i] = False

    @torch.no_grad()
    def _soft_update(self, source, target):
        for tp, sp in zip(target.parameters(), source.parameters()):
            tp.data.mul_(1.0 - self.tau)
            tp.data.add_(self.tau * sp.data)

    def _train_step(self):
        states, actions, rewards, next_states, dones, goals = self.replay.sample(
            self.batch_size, self.rng
        )
        states = states.to(self.device, dtype=self._dtype)
        goal = goals.to(self.device, dtype=self._dtype)
        actions = actions.to(self.device, dtype=self._dtype)
        rewards = rewards.to(self.device, dtype=self._dtype)
        next_states = next_states.to(self.device, dtype=self._dtype)
        dones = dones.to(self.device, dtype=self._dtype)

        with torch.no_grad():
            next_actions = self.actor_target(next_states, goal)
            target_q = self.critic_target(
                next_states, next_actions, goal
            )
            target = rewards + self.gamma * (1.0 - dones) * target_q

        q = self.critic(states, actions, goal)
        critic_loss = torch.nn.functional.mse_loss(q, target)

        self.critic_optimizer.zero_grad(set_to_none=True)
        critic_loss.backward()
        torch.nn.utils.clip_grad_norm_(self.critic.parameters(), 10.0)
        self.critic_optimizer.step()

        policy_actions = self.actor(states, goal)
        actor_loss = -self.critic(
            states, policy_actions, goal
        ).mean()

        self.actor_optimizer.zero_grad(set_to_none=True)
        actor_loss.backward()
        torch.nn.utils.clip_grad_norm_(self.actor.parameters(), 10.0)
        self.actor_optimizer.step()

        self._soft_update(self.actor, self.actor_target)
        self._soft_update(self.critic, self.critic_target)

        return (
            float(critic_loss.detach().cpu()),
            float(actor_loss.detach().cpu()),
        )

    def _train(self, goal_state):
        if self.replay.size < max(self.warmup_size, self.batch_size):
            return

        q_losses, actor_losses = [], []
        for _ in range(self.train_steps):
            q, a = self._train_step()
            q_losses.append(q)
            actor_losses.append(a)

        self._last_q_loss = float(np.mean(q_losses))
        self._last_actor_loss = float(np.mean(actor_losses))
        print('Q loss : ', self._last_q_loss)
        print('Actor loss : ', self._last_actor_loss)

    def _plan(self, root_state, goal_state):
        state = root_state.copy()
        actions = []

        state_history, action_history = self._init_history(root_state, 1)

        for t in range(self.horizon):
            action = self._policy_action(
                state[None], goal_state[None], explore=False
            )[0]
            actions.append(action)

            action_history = np.concatenate(
                [action_history[:, 1:], action[None, None, :]], axis=1
            )

            next_state = self._transition_latent(
                state_history[:,-min(t+1, self._history_size):], action_history[:,-min(t+1, self._history_size):]
            )[0]

            state_history = np.concatenate(
                [state_history[:, 1:], next_state[None, None, :]], axis=1
            )
            state = next_state

            if np.linalg.norm(state - goal_state) <= self.goal_radius:
                break

        while len(actions) < self.horizon:
            actions.append(np.zeros(self.action_dim, dtype=np.float32))

        return torch.as_tensor(
            np.stack(actions[:self.horizon]),
            dtype=self._dtype,
            device=self.device,
        )

    def _plan_single(self, info_dict, init_action=None, env_idx=None):
        root_state = np.asarray(
            self._state_from_info(info_dict), dtype=np.float32
        ).reshape(-1)

        goal_state = np.asarray(
            self._goal_from_info(info_dict), dtype=np.float32
        ).reshape(-1)

        if not self._networks_initialized:
            self._init_networks(root_state.size)

        for _ in range(self.planning_iterations):
            self._collect_imagined_data(
                root_state,
                goal_state,
                self.rollout_batch_size,
            )
            self._train(goal_state)

        return self._plan(root_state, goal_state)

    def solve(self, info_dict: dict, init_action=None):
        start = time.perf_counter()

        if not info_dict:
            return {
                "actions": torch.zeros(
                    (0, self.horizon, self.action_dim),
                    dtype=self._dtype,
                    device=self.device,
                )
            }

        total_envs = len(next(iter(info_dict.values())))
        actions = []

        for env_idx in range(total_envs):
            env_info = {
                k: self._select(v, env_idx)
                for k, v in info_dict.items()
            }
            env_init = (
                None if init_action is None
                else self._select(init_action, env_idx)
            )
            actions.append(
                self._plan_single(env_info, env_init, env_idx)
            )
            self.replay.reset() #OPTIONAL
            self._init_networks(self._state_from_info(env_info).shape[-1]) #OPTIONAL
            print('------------------------------------')

        print("TIME SOLVE DEEP Q", time.perf_counter() - start)
        if self._last_q_loss is not None:
            print(
                "Q LOSS:", self._last_q_loss,
                "ACTOR LOSS:", self._last_actor_loss,
            )

        return {"actions": torch.stack(actions, dim=0).to(self.device)}